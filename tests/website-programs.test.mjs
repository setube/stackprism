test('新增网站程序在真实 page-detector 里按页面特征命中', async () => {
  for (const [name, fixture] of pageCases) {
    const technologies = await runPageDetector(pageRules, fixture)
    assert.ok(
      technologies.some(tech => tech.name === name),
      `${name} 未命中：${JSON.stringify(fixture).slice(0, 160)} => ${technologies.map(tech => tech.name).join(', ')}`
    )
  }
})

test('正文里提到程序名、通用路径和常见全局变量时不误判', async () => {
  const newNames = new Set(pageCases.map(([name]) => name))
  const technologies = await runPageDetector(pageRules, {
    href: 'https://blog.example.com/posts/1',
    html: html(
      [
        '<p>对比了 Answer、Medium、MetInfo、YApi、TiddlyWiki、Doxygen、Gridsome、NotionNext、Symphony 和 PbootCMS。</p>',
        '<p>generator 字段示例：content="Hexo"，路径 /static/js/home.js、/assets/js/require.js、/pub/lib/、/r/cms/</p>',
        '<a href="https://github.com/apache/answer">apache/answer</a> <a href="https://namelessmc.com">NamelessMC</a>',
        '<div id="yapi-doc"></div><title>Powered by DouPHP 教程</title>'
      ].join('')
    ),
    resources: [
      'https://cdn.jsdelivr.net/npm/jquery@3.7.1/dist/jquery.min.js',
      'https://blog.example.com/static/js/home.js',
      'https://blog.example.com/assets/js/require.min.js',
      'https://blog.example.com/api/languages/list',
      'https://blog.example.com/static/misago-fan-art.png'
    ],
    globals: ['jQuery', 'Label', 'Config', 'config'],
    classes: ['btn', 'crayon', 'nextra', 'van-main']
  })
  // technologies 来自 vm 里的数组，先转成当前环境的数组再比较
  const wrong = Array.from(
    technologies.filter(tech => newNames.has(tech.name)),
    tech => tech.name
  )
  assert.deepEqual(wrong, [])
})

test('WordPress 插件目录不当成 October CMS 插件目录', async () => {
  const has = async (url, name) =>
    (await runPageDetector(pageRules, { href: 'https://www.example.com/', resources: [url] })).some(tech => tech.name === name)
  assert.equal(await has('https://www.example.com/wp-content/plugins/genesis-blocks/dist/assets/js/dismiss.js', 'October CMS'), false)
  assert.ok(await has('https://www.example.com/plugins/rainlab/blog/assets/js/post-form.js', 'October CMS'))
})

