test('新增网站程序的响应头与 Cookie 规则按单个特征命中', async () => {
  const headersModule = await loadHeadersModule()
  const headerRules = loadHeaderRules()
  for (const [name, headers] of headerCases) {
    const technologies = detectHeaders(headersModule, headerRules, headers)
    assert.ok(
      technologies.some(tech => tech.name === name),
      `${name} 未命中：${JSON.stringify(headers)} => ${technologies.map(tech => tech.name).join(', ')}`
    )
  }

  const headerNames = new Set(headerCases.map(([name]) => name))
  const generic = detectHeaders(headersModule, headerRules, {
    server: 'nginx/1.25.3',
    'x-powered-by': 'PHP/8.3.2',
    'set-cookie': ['PHPSESSID=abc; path=/', 'laravel_session=abc; path=/', 'XSRF-TOKEN=abc; path=/', 'my_qa_key_backup=1; path=/'],
    'x-cache': 'HIT'
  })
  assert.deepEqual(
    generic.filter(tech => headerNames.has(tech.name)).map(tech => tech.name),
    []
  )
})
